test("Sprint 2 creates actual reactive WebGL geometry and independent spores",async({page})=>{
  test.setTimeout(90000);
  await page.goto("http://127.0.0.1:8765/sandbox.html");
  const studio=page.locator("#myco-visual-builder");
  await expect(studio.locator("#mb-live-canvas")).toBeVisible({timeout:30000});
  await expect.poll(()=>page.evaluate(()=>window.MycoSimCreative3D?.getState()?.meshCount),{timeout:25000}).toBeGreaterThan(10);
  const before=await page.evaluate(()=>window.MycoSimCreative3D.getState());
  expect(before.form).toBe("agaric");
  await studio.locator('[data-mb-choice="cap"][data-mb-value="conical"]').click();
  expect((await page.evaluate(()=>window.MycoSimCreative3D.getState())).cap).toBe("convex");
  await studio.locator("#mb-apply").click();
  await expect.poll(()=>page.evaluate(()=>window.MycoSimCreative3D.getState().cap)).toBe("conical");
  await studio.locator('[data-mb-choice="surface"][data-mb-value="teeth"]').click();
  await studio.locator("#mb-apply").click();
  await expect(studio.locator("#mb-3d-feedback")).toContainText("teeth");
  const teeth=await page.evaluate(()=>window.MycoSimCreative3D.getState());
  expect(teeth.meshCount).toBeGreaterThan(30);
  await studio.locator('[data-mb-choice="stipe"][data-mb-value="bulbous"]').click();
  await studio.locator("#mb-apply").click();
  await studio.locator('[data-mb-choice="attachment"][data-mb-value="decurrent"]').click();
  await studio.locator("#mb-apply").click();
  await expect(studio.locator("#mb-3d-feedback")).toContainText("bulbous");
  await expect(studio.locator("#mb-3d-feedback")).toContainText("decurrent");
  await studio.locator('[data-mb-choice="spore"][data-mb-value="fusiform"]').click();
  await studio.locator("#mb-apply").click();
  await expect(studio.locator("#mb-microscopy")).toContainText("fusiform");
  await studio.locator('[data-mb-choice="form"][data-mb-value="cup"]').click();
  await studio.locator("#mb-apply").click();
  await expect(studio.locator("#mb-3d-feedback")).toContainText("cup");
  const cup=await page.evaluate(()=>window.MycoSimCreative3D.getState());
  expect(cup.meshCount).toBeLessThan(teeth.meshCount);
  await studio.locator("#mb-reset").click();
  await expect.poll(()=>page.evaluate(()=>window.MycoSimCreative3D?.getState()?.form)).toBe("agaric");
  await expect(studio.locator("#mb-microscopy")).toContainText("ellipsoid");
  expect(await page.locator("#observationForm").count()).toBe(1);
});

test("Studio advanced choices alter original engine, not evidence records",async({page})=>{
  test.setTimeout(90000);
  await page.goto("http://127.0.0.1:8765/sandbox.html");
  const studio=page.locator("#myco-visual-builder");
  await expect(studio).toBeVisible({timeout:30000});
  await expect.poll(()=>page.evaluate(()=>Boolean(window.MycoSimMorphologyBridge)),{timeout:30000}).toBe(true);
  const before=await page.evaluate(()=>window.MycoSimMorphologyBridge.getState().variants.agaric_stipe_surface_mid);
  await studio.locator('[data-mb-region="stipe"]').click();
  await studio.locator('[data-mb-advanced="agaric_stipe_surface_mid"][data-mb-option="reticulate"]').click();
  expect(await page.evaluate(()=>window.MycoSimMorphologyBridge.getState().variants.agaric_stipe_surface_mid)).toBe(before);
  await studio.locator("#mb-apply").click();
  await expect.poll(()=>page.evaluate(()=>window.MycoSimMorphologyBridge.getState().variants.agaric_stipe_surface_mid),{timeout:30000}).toBe("reticulate");
  await studio.locator('[data-mb-region="hymenophore"]').click();
  await studio.locator('[data-mb-advanced="agaric_gill_attachment"][data-mb-option="decurrent"]').click();
  await studio.locator("#mb-apply").click();
  await expect.poll(()=>page.evaluate(()=>window.MycoSimMorphologyBridge.getState().variants.agaric_gill_attachment),{timeout:30000}).toBe("decurrent");
  expect(await page.locator("#observationForm").count()).toBe(1);
  expect(await studio.locator("#mb-region-editor button").count()).toBeGreaterThan(10);
});

test("Scientific form immediately drives visual morphology without inventing evidence",async({page})=>{
  test.setTimeout(90000);
  await page.goto("http://127.0.0.1:8765/sandbox.html");
  await expect.poll(()=>page.evaluate(()=>Boolean(window.MycoSimMorphologyBridge)),{timeout:30000}).toBe(true);
  const form=page.locator("#observationForm");
  await expect(form.locator('[data-obs-value="cap_morphology"]')).toBeVisible({timeout:30000});
  await form.locator('[data-obs-value="cap_morphology"]').selectOption("conical");
  await expect.poll(()=>page.evaluate(()=>window.MycoSimMorphologyBridge.getState().variants.agaric_pileus_profile)).toBe("conical");
  await expect(page.locator("#observationVisualStatus")).toContainText("3D teaching model updated");
  await expect(form.locator('[data-obs-state="cap_morphology"]')).toHaveValue("not_examined");
  await expect(form.locator('[data-obs-provenance="cap_morphology"]')).toHaveValue("");
  await form.locator('[data-obs-value="stipe_morphology"]').selectOption("bulbous");
  await expect.poll(()=>page.evaluate(()=>window.MycoSimMorphologyBridge.getState().variants.agaric_stipe_form)).toBe("bulbous_base");
  await form.locator('[data-obs-value="hymenophore_type"]').selectOption("free_gills");
  await expect.poll(()=>page.evaluate(()=>window.MycoSimMorphologyBridge.getState().variants.agaric_gill_attachment)).toBe("free_gills");
  await form.locator('[data-obs-value="spore_shape"]').selectOption("fusiform");
  await expect(page.locator("#mb-microscopy")).toContainText("fusiform");
  await form.locator('[data-obs-value="ornamentation"]').selectOption("warted");
  await expect(page.locator("#observationVisualStatus")).toContainText("no validated geometric representation");
  await expect(form.locator('[data-obs-state="ornamentation"]')).toHaveValue("not_examined");
});

test("Sprint 3 keeps the laboratory in view while updating authoritative 3D and scientific evidence remains unexamined",async({page})=>{
  test.setTimeout(90000);
  await page.setViewportSize({width:390,height:844});
  await page.goto("http://127.0.0.1:8765/sandbox.html");
  await expect.poll(()=>page.evaluate(()=>Boolean(window.MycoSimMorphologyBridge)),{timeout:30000}).toBe(true);
  const select=page.locator('[data-obs-value="cap_morphology"]');
  await expect(select).toBeVisible({timeout:30000});
  await select.scrollIntoViewIfNeeded();
  await page.evaluate(()=>document.querySelector('[data-obs-value="cap_morphology"]').focus());
  const before=await page.evaluate(()=>({scrollY:window.scrollY,step:document.querySelector(".learning-step.active")?.dataset.learningStep,mode:document.body.dataset.learnerMode}));
  await select.selectOption("campanulate");
  await expect.poll(()=>page.evaluate(()=>window.MycoSimMorphologyBridge.getState().variants.agaric_pileus_profile)).toBe("campanulate");
  await page.waitForTimeout(850);
  const after=await page.evaluate(()=>({scrollY:window.scrollY,step:document.querySelector(".learning-step.active")?.dataset.learningStep,mode:document.body.dataset.learnerMode}));
  expect(Math.abs(after.scrollY-before.scrollY)).toBeLessThan(85);
  expect(after.step).toBe(before.step);
  expect(after.mode).toBe(before.mode);
  await expect(page.locator('[data-obs-state="cap_morphology"]')).toHaveValue("not_examined");
  await expect(page.locator('[data-obs-provenance="cap_morphology"]')).toHaveValue("");
  await expect(page.locator("#mycosim-view-authoritative-specimen")).toHaveAttribute("href","#stage");
  await select.selectOption("hoof");
  await expect.poll(()=>page.evaluate(()=>window.MycoSimMorphologyBridge.getState().family)).toBe("hoof_conk");
  await select.selectOption("conical");
  await expect.poll(()=>page.evaluate(()=>window.MycoSimMorphologyBridge.getState().family)).toBe("agaricoid");
  await page.locator('[data-obs-value="hymenophore_type"]').selectOption("folds");
  await expect(page.locator("#observationVisualStatus")).toContainText("no validated geometric representation");
});
